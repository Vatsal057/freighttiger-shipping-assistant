"""Command-line interface for the FreightTiger Smart Shipping Cost Assistant.

Commands:
  run                  Run the end-to-end pipeline and save output CSV.
  verify-reproducibility Run pipeline 3 times and verify matching SHA-256 hashes.
  cost-log             Display token and model cost accounting for the run.
  query                Interactive stretch goal: ask questions in plain English.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys

# Ensure project root is on sys.path
ROOT_DIR = Path(__file__).resolve().parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from src.pipeline import (
    run_pipeline,
    write_submission_csv,
    answer_natural_language_query,
)
from src.justification import load_context_notes

DEFAULT_SHIPMENTS = Path("AI Intern Case Study/shipment_records.csv")
DEFAULT_NOTES = Path("AI Intern Case Study/context_notes.csv")
DEFAULT_OUTPUT = Path("submission_output.csv")


def compute_file_sha256(file_path: Path) -> str:
    """Compute SHA-256 hash of a file."""
    hasher = hashlib.sha256()
    with open(file_path, "rb") as f:
        while chunk := f.read(65536):
            hasher.update(chunk)
    return hasher.hexdigest()


def cmd_run(args: argparse.Namespace) -> None:
    """Execute analysis pipeline and output CSV."""
    print("Running FreightTiger Shipping Cost Assistant...")
    out_df = run_pipeline(
        shipments_path=args.shipments,
        notes_path=args.notes,
        hist_threshold_pct=args.hist_threshold,
        peer_threshold_pct=args.peer_threshold,
    )

    out_path = Path(args.output)
    write_submission_csv(out_df, out_path)
    file_hash = compute_file_sha256(out_path)

    print(f"Analysis complete. Total evaluated flags: {len(out_df)}")
    print(f"Saved output CSV to: {out_path}")
    print(f"SHA-256 Hash: {file_hash}")
    print("\nFirst 5 rows of output:")
    print(out_df.head(5).to_string(index=False))


def cmd_verify_reproducibility(args: argparse.Namespace) -> None:
    """Execute pipeline 3 times and check that SHA-256 hashes are identical."""
    print("Executing 3 untouched reproducibility runs on the input dataset...")
    hashes = []

    for run_idx in range(1, 4):
        run_file = Path(f"output/run_{run_idx}_output.csv")
        out_df = run_pipeline(
            shipments_path=args.shipments,
            notes_path=args.notes,
            hist_threshold_pct=args.hist_threshold,
            peer_threshold_pct=args.peer_threshold,
        )
        write_submission_csv(out_df, run_file)
        h = compute_file_sha256(run_file)
        hashes.append((run_idx, run_file, h))
        print(f"Run {run_idx}: {run_file} -> SHA-256: {h}")

    unique_hashes = set(h for _, _, h in hashes)
    print("\nReproducibility summary:")
    if len(unique_hashes) == 1:
        print(f"All 3 runs generated byte-identical output.")
        print(f"SHA-256: {hashes[0][2]}")
    else:
        print(f"Outputs diverged across runs: {unique_hashes}")
        sys.exit(1)


def cmd_cost_log(args: argparse.Namespace) -> None:
    """Print token and model cost accounting for one full pipeline run."""
    from src.llm_client import AdaptiveLLMClient

    out_df = run_pipeline(args.shipments, args.notes)
    client = AdaptiveLLMClient()

    total_in = 0
    total_out = 0
    total_cost = 0.0

    for _, row in out_df.iterrows():
        prompt = (
            f"Route {row['route']} on week {row['week_of']} had cost INR {row['cost_per_tonne_km']}/t-km "
            f"({row['vs_own_history']}; {row['vs_similar_routes']}). "
            f"Matched Note: {row['matched_note_id']}."
        )
        res = client.generate(prompt=prompt, deterministic_fallback_text=str(row["reason"]))
        total_in += res.input_tokens
        total_out += res.output_tokens
        total_cost += res.cost_usd

    print("Cost and token log (one full run over shipment records):")
    print(f"  Target model: {res.model_name}")
    print(f"  Provider tier: {res.provider}")
    print(f"  Total LLM calls: {len(out_df)}")
    print(f"  Total input tokens: {total_in:,}")
    print(f"  Total output tokens: {total_out:,}")
    print(f"  Total tokens: {total_in + total_out:,}")
    print(f"  Estimated cost (USD): ${total_cost:.5f}")
    print("  Note: Rates based on published LLaMA-3.3-70B pricing ($0.59/1M input, $0.79/1M output).")



def cmd_query(args: argparse.Namespace) -> None:
    """Interactive plain-English inquiry into assistant findings."""
    out_df = run_pipeline(args.shipments, args.notes)
    notes = load_context_notes(args.notes)
    query_str = " ".join(args.question)
    print(f"Question: \"{query_str}\"\n")
    ans = answer_natural_language_query(query_str, out_df, notes)
    print(ans)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="FreightTiger Smart Shipping Cost Assistant CLI"
    )
    parser.add_argument(
        "--shipments",
        type=Path,
        default=DEFAULT_SHIPMENTS,
        help="Path to shipment_records.csv",
    )
    parser.add_argument(
        "--notes",
        type=Path,
        default=DEFAULT_NOTES,
        help="Path to context_notes.csv",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="Output CSV path",
    )
    parser.add_argument(
        "--hist-threshold",
        type=float,
        default=15.0,
        help="Threshold %% vs trailing own history to trigger flag",
    )
    parser.add_argument(
        "--peer-threshold",
        type=float,
        default=20.0,
        help="Threshold %% vs peer routes to trigger flag",
    )

    subparsers = parser.add_subparsers(dest="command")

    # run command
    subparsers.add_parser("run", help="Run full pipeline and generate output CSV")

    # verify-reproducibility command
    subparsers.add_parser(
        "verify-reproducibility",
        help="Run 3 consecutive runs and verify SHA-256 hash match",
    )

    # cost-log command
    subparsers.add_parser("cost-log", help="Display token and cost accounting")

    # query command
    query_parser = subparsers.add_parser("query", help="Ask a question in plain English")
    query_parser.add_argument("question", nargs="+", help="Natural language question")

    args = parser.parse_args()

    if args.command == "run" or args.command is None:
        cmd_run(args)
    elif args.command == "verify-reproducibility":
        cmd_verify_reproducibility(args)
    elif args.command == "cost-log":
        cmd_cost_log(args)
    elif args.command == "query":
        cmd_query(args)


if __name__ == "__main__":
    main()
